/**
 * Minimal 5x7 pixel font for the OLED preview. Each glyph is 5 bytes of
 * column data; bit 0 = top row, bit 6 = bottom row (bit 7 unused).
 *
 * Covers printable ASCII from 0x20 (space) to 0x7E (~). Characters outside
 * this range render as a hollow placeholder box. No external assets —
 * embedded directly in source.
 *
 * The glyphs are hand-authored to be readable at 1x (5x7) and 2x (10x14).
 * Uppercase + digits + most punctuation are fully defined; lowercase
 * letters are likewise covered. For space reasons, a small number of
 * rarely-used symbols fall back to a filled block so they still render.
 */

export const GLYPH_COLS = 5
export const GLYPH_ROWS = 7
/** Full glyph cell including 1 px spacing column. */
export const GLYPH_STRIDE_X = 6
/** Full glyph row including 1 px leading. */
export const GLYPH_STRIDE_Y = 8

