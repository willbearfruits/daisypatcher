const MISSING: [number, number, number, number, number] = [0x7f, 0x41, 0x41, 0x41, 0x7f]

export function glyphColumns(codePoint: number): [number, number, number, number, number] {
  const g = FONT[codePoint]
  return g ?? MISSING
}

/** Measure the pixel width of a rendered string (including 1px trailing space). */
export function textWidth(text: string, size: 1 | 2): number {
  if (text.length === 0) return 0
  return text.length * GLYPH_STRIDE_X * size
}
